"""Durable current assessment/job per user and field, with lease-based compare-and-set."""
from typing import Protocol


class EvidenceAssessmentRepository(Protocol):
    async def list_for_user(self, user_id: str) -> list[dict]: ...
    async def enqueue(self, record: dict) -> None: ...
    async def claim(self) -> dict | None: ...
    async def finish(self, job: dict, result: dict, *, retry: bool = False) -> bool: ...
    async def discard(self, job: dict) -> None: ...
    async def remove(self, user_id: str, key: str) -> None: ...
